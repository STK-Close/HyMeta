// Wraps src/app.html (the app, written as one page) into a complete web page and saves it as
// lib/page.js. The server hands that page out only after sign-in, so it must not sit in web/,
// which is public. web/ holds only icons, artwork and other files anyone may fetch.
const fs = require("fs"), path = require("path");
const root = path.join(__dirname, "..");
const src = fs.readFileSync(path.join(root, "src/app.html"), "utf8");
const cut = src.indexOf('<div class="app">');
const headBits = src.slice(0, cut).replace(/<title>.*?<\/title>\s*/s, "").replace(/<meta name="claude:[^>]*>\s*/g, "");
const page = `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">
<title>HyMeta</title>
<meta name="description" content="Playpacks for Hytale: sets of mods picked to work together, one for every way you like to play.">
<meta name="robots" content="noindex, nofollow">
<meta name="hymeta-server" content="1">
<meta name="theme-color" content="#0e1223">
<meta name="apple-mobile-web-app-title" content="HyMeta">
<meta name="apple-mobile-web-app-capable" content="yes">
<link rel="icon" href="/icon.svg" type="image/svg+xml">
<link rel="icon" href="/favicon-32.png" sizes="32x32" type="image/png">
<link rel="apple-touch-icon" href="/apple-touch-icon.png">
<link rel="manifest" href="/manifest.webmanifest">
<meta property="og:title" content="HyMeta">
<meta property="og:description" content="Playpacks for Hytale: sets of mods picked to work together.">
<meta property="og:image" content="/og.png">
<meta name="twitter:card" content="summary_large_image">
<style>:root{padding-top:env(safe-area-inset-top,0px);padding-bottom:env(safe-area-inset-bottom,0px)}img{max-width:100%}[hidden]{display:none!important}</style>
${headBits.trim()}
</head>
<body>
${src.slice(cut).trim()}
</body>
</html>
`;
fs.writeFileSync(path.join(root, "lib/page.js"), "// Generated by scripts/build.js from src/app.html. Do not edit by hand.\nmodule.exports = " + JSON.stringify(page) + ";\n");
console.log("Built lib/page.js (" + page.length + " characters)");

// The legal pages, as plain pages anyone may read without entering the site. They are made from
// the very same words the app shows under You, Help and legal, so the two can never drift apart.
const { shell } = require("../lib/shell");
const docsAt = src.indexOf("var DOCS = {"), docsEnd = src.indexOf("\n};", docsAt);
const DOCS = new Function("return " + src.slice(docsAt + "var DOCS = ".length, docsEnd + 2))();
const PAGES = [["terms", "terms"], ["privacy", "privacy"], ["rules", "rules"], ["support", "help"], ["credits", "credits"]];
for (const [key, file] of PAGES) {
  const nav = '<nav aria-label="Legal pages"><ul>' + PAGES.map(([k, f]) => '<li><a href="/' + f + '.html"' + (k === key ? ' aria-current="page"' : "") + ">" + DOCS[k][0] + "</a></li>").join("") + "</ul></nav>";
  fs.writeFileSync(path.join(root, "web", file + ".html"), shell(DOCS[key][0], nav + '<h1 id="doc-title">' + DOCS[key][0] + '</h1><div class="doc">' + DOCS[key][1] + '</div><a class="back" href="/">Back to HyMeta</a>'));
}
console.log("Built " + PAGES.length + " legal pages in web/");
