// Checks the community playpack rules against a throwaway in-memory database.
// Run: node tests/community.test.js
process.env.HYMETA_LOCAL_DB = "1";
const a = require("../lib/accounts"), c = require("../lib/community");
(async () => {
  const problems = [], bad = (m) => problems.push(m);
  const refuses = async (label, fn, pattern) => { try { await fn(); bad(label + ": was allowed"); } catch (e) { if (e.code !== "invalid" || (pattern && !pattern.test(e.message))) bad(label + ": wrong refusal: " + e.message); } };
  const make = async (email, name) => a.currentUser({ headers: { cookie: (await a.signUp({ email, password: "correct-horse-9", name, over13: true })).split(";")[0] } });
  const owner = await make("owner@example.test", "The Owner"), ann = await make("ann@example.test", "Ann Builder"), bob = await make("bob@example.test", "Bob Player");
  if (!(await a.isOwner(owner)) || (await a.isOwner(ann))) bad("the first account should be the owner, and only that one");
  process.env.OWNER_EMAILS = "someone@example.test, BOB@example.test"; if (!(await a.isOwner(bob)) || (await a.isOwner(ann))) bad("an email listed as an owner in the host settings should be an owner");
  delete process.env.OWNER_EMAILS; if (await a.isOwner(bob)) bad("owner status stayed after the setting was removed");
  const mods = ["cf1", "cf2", "cf3"], good = { name: "Swamp wizard", blurb: "Mud and magic.", mods };
  await refuses("two mods", () => c.submit(ann, { ...good, mods: ["cf1", "cf2"] }), /three mods/);
  await refuses("twenty-one mods", () => c.submit(ann, { ...good, mods: Array.from({ length: 21 }, (_, i) => "cf" + (i + 1)) }), /20 mods/);
  await refuses("made-up mod id", () => c.submit(ann, { ...good, mods: ["cf1", "cf2", "<script>"] }));
  await refuses("phone number", () => c.submit(ann, { ...good, blurb: "call 5551234567" }), /links, emails/);
  await refuses("rude name", () => c.submit(ann, { ...good, name: "Sexy pack" }), /friendly/);
  await refuses("no name", () => c.submit(ann, { ...good, name: " " }), /name/i);
  const id = await c.submit(ann, good);
  if ((await c.view(bob)).packs.length) bad("a playpack still waiting for review is shown to other members");
  const annView = await c.view(ann);
  if (annView.mine.length !== 1 || annView.mine[0].status !== "pending" || annView.packs.length) bad("the builder should see their own waiting playpack, under their own list only");
  if ((await c.queue()).waiting.length !== 1) bad("the waiting playpack is not in the owner's queue");
  await c.review({ id, approve: true });
  const seen = (await c.view(bob)).packs[0];
  if (!seen || seen.by !== "Ann Builder" || seen.mods.join() !== mods.join() || seen.mine) bad("an approved playpack should be shown to others with its builder's display name");
  if (JSON.stringify(seen).includes("ann@example.test")) bad("a member's email is shown with their playpack");
  await refuses("reporting your own", () => c.report(ann, { id, why: 0 }));
  await c.report(bob, { id, why: 1 }); await c.report(bob, { id, why: 1 });
  if ((await c.view(bob)).packs.length) bad("a reported playpack is still shown to the member who reported it");
  if ((await c.view(owner)).packs.length !== 1) bad("one member's report hid the playpack from everyone");
  const q = await c.queue();
  if (q.reported.length !== 1 || q.reported[0].count !== 1 || !/personal/.test(q.reported[0].reasons)) bad("the report did not reach the owner's queue correctly: " + JSON.stringify(q.reported));
  await c.dismiss({ id }); if ((await c.queue()).reported.length) bad("dismissing a report left it in the queue");
  const id2 = await c.submit(ann, { ...good, name: "Second pack" }); await c.review({ id: id2, approve: true });
  await c.block(owner, { id });
  const ownerView = await c.view(owner);
  if (ownerView.packs.length || ownerView.blocked.length !== 1 || ownerView.blocked[0].name !== "Ann Builder") bad("blocking a member should hide all of their playpacks and list them as blocked");
  await c.unblock(owner, { author: ownerView.blocked[0].id }); if ((await c.view(owner)).packs.length !== 2) bad("unblocking did not bring the playpacks back");
  await c.review({ id: id2, approve: false });
  if ((await c.view(owner)).packs.some((p) => p.id === id2)) bad("a rejected playpack is still shown");
  const rejected = (await c.view(ann)).mine.find((p) => p.id === id2);
  if (!rejected || rejected.status !== "rejected" || !rejected.reason) bad("the builder is not told their playpack was not approved");
  await c.remove(bob, { id }); if (!(await c.one(id))) bad("a member deleted someone else's playpack");
  for (let i = 0; i < 5; i++) await c.submit(bob, { ...good, name: "Bob pack " + i });
  await refuses("sixth waiting playpack", () => c.submit(bob, { ...good, name: "One too many" }), /waiting for review/);
  await a.deleteAccount(ann);
  if ((await c.view(owner)).packs.some((p) => p.by === "Ann Builder") || (await c.one(id))) bad("deleting an account left its playpacks behind");
  console.log(problems.length ? problems.join("\n") : "COMMUNITY OK");
  process.exit(problems.length ? 1 : 0);
})().catch((e) => { console.error("FAILED", e); process.exit(1); });
